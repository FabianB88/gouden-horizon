export function addWorldWalkways(areas,world){
 for(const [id,routes]of Object.entries(WORLD_WALKWAYS)){
  const area=areas[id],scale=(area.bounds?.width||world.width)/1536;
  const native=poly=>poly.map(([x,y])=>[x*scale/world.width,y*scale/world.height]);
  for(const [width,points]of routes)for(let i=1;i<points.length;i++){
   const [a,b]=[points[i-1],points[i]],dx=b[0]-a[0],dy=b[1]-a[1],length=Math.hypot(dx,dy),nx=-dy/length*width,ny=dx/length*width;
   area.nav.push(native([[a[0]+nx,a[1]+ny],[b[0]+nx,b[1]+ny],[b[0]-nx,b[1]-ny],[a[0]-nx,a[1]-ny]]));
   // Rounded landings overlap both segments, so bends do not pinch the hero.
   for(const p of [a,b])area.nav.push(native(Array.from({length:12},(_,j)=>[p[0]+Math.cos(j*Math.PI/6)*width,p[1]+Math.sin(j*Math.PI/6)*width])));
  }
 }
}
