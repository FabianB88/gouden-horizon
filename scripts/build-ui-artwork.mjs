import {readdirSync,statSync,writeFileSync} from 'node:fs';
import {AREAS} from '../src/data.js?v=45';
import {PROLOGUE} from '../src/lore.js?v=45';
const items=readdirSync(new URL('../assets/items/',import.meta.url)).filter(f=>f.endsWith('.webp')).map(f=>'assets/items/'+f);
const previews=[...new Set(AREAS.map(a=>'assets/painted/previews/'+a.file))];
const portraits=readdirSync(new URL('../assets/painted/',import.meta.url)).filter(f=>f.startsWith('portrait-')&&f.endsWith('.webp')).map(f=>'assets/painted/'+f);
const lore=PROLOGUE.map(p=>'assets/painted/'+p.image);
const files=[...new Set([...items,...previews,...portraits,...lore])];let bytes=0;for(const file of files)bytes+=statSync(new URL('../'+file,import.meta.url)).size;
writeFileSync(new URL('../src/ui-artwork.js',import.meta.url),'// Generated by scripts/build-ui-artwork.mjs. Icons and menu images are ready before play.\nexport const UI_ARTWORK='+JSON.stringify(files)+';\n');
console.log('Prepared '+files.length+' interface images ('+bytes+' compressed bytes).');
